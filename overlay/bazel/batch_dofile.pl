# Batched version of util/dofile.pl for Bazel.
#
# Processes multiple OpenSSL .in templates in a single Perl invocation,
# writing each result directly to its output file.  This avoids the
# per-template process-creation overhead that dominates on Windows.
#
# Usage: batch_dofile.pl --in=<template> --out=<output> [--in=... --out=...] ...
#
# Arguments of the form @<file> name a Bazel params file containing one
# argument per line; they are expanded in place.
#
# Must be invoked with -Mconfigdata (and any other -M flags the
# templates need, e.g. -Moids_to_c).

use strict;
use warnings;

use FindBin;
use Symbol ();
use lib "$FindBin::Bin/perl";
use OpenSSL::fallback "$FindBin::Bin/../external/perl/MODULES.txt";
use OpenSSL::Template;

# OpenSSL renders every template in its own perl process. Some helper modules
# keep process-global state that would leak between templates when batched:
# OpenSSL::OID (used via oids_to_c) registers every OID it parses, and an OID
# registered as a leaf by one .asn1 file silently becomes an arc once another
# file uses it as a parent, changing what process_leaves() emits. To keep the
# per-process semantics, both modules are unloaded and oids_to_c re-required
# (which pulls in a fresh OpenSSL::OID) before each template.
sub reset_stateful_modules {
    return unless exists $INC{'oids_to_c.pm'};
    for my $mod (qw(oids_to_c OpenSSL::OID)) {
        (my $file = "$mod.pm") =~ s{::}{/}g;
        delete $INC{$file};
        Symbol::delete_package($mod);
    }
    require oids_to_c;
}

die "You must run this script with -Mconfigdata\n"
    if !exists($config{target});

# Expand param files, if any.
my @args;
for my $arg (@ARGV) {
    if ($arg =~ /^@(.+)$/) {
        open(my $fh, '<', $1)
            or die "Can't open params file $1: $!\n";
        while (my $line = <$fh>) {
            $line =~ s/\r?\n$//;
            push @args, $line;
        }
        close $fh;
    } else {
        push @args, $arg;
    }
}

my @pairs;
my $i = 0;
while ($i < scalar(@args)) {
    my $arg = $args[$i];
    if ($arg =~ /^--in=(.+)$/) {
        my $in = $1;
        $i++;
        die "Expected --out=<path> after --in=$in\n"
            if $i >= scalar(@args) || $args[$i] !~ /^--out=(.+)$/;
        push @pairs, { in => $in, out => $1 };
    } else {
        die "Unexpected argument: $arg\n";
    }
    $i++;
}

die "No --in/--out pairs given\n" unless @pairs;

my @autowarntext = (
    "WARNING: do not edit!",
    "Generated by batch_dofile.pl"
);

my $failed = 0;
sub errorcallback {
    my %args = @_;
    print STDERR $args{error};
    $failed++;
    return undef;
}

my $prepend = <<"_____";
use File::Spec::Functions;
use lib '$FindBin::Bin/../Configurations';
use lib '$config{builddir}';
use platform;
_____

for my $pair (@pairs) {
    reset_stateful_modules();

    my $template = OpenSSL::Template->new(
        TYPE     => 'FILE',
        SOURCE   => $pair->{in},
        FILENAME => $pair->{in},
    );
    die "Couldn't create template for $pair->{in}: $Text::Template::ERROR\n"
        if !defined($template);

    my $result = $template->fill_in(
        TYPE     => 'FILE',
        SOURCE   => $pair->{in},
        FILENAME => $pair->{in},
        HASH     => {
            config       => \%config,
            target       => \%target,
            disabled     => \%disabled,
            withargs     => \%withargs,
            unified_info => \%unified_info,
            autowarntext => \@autowarntext,
        },
        BROKEN  => \&errorcallback,
        PREPEND => $prepend,
        PACKAGE => 'OpenSSL::safe',
    );
    exit 1 if $failed;

    open(my $fh, '>', $pair->{out})
        or die "Can't open $pair->{out}: $!\n";
    print $fh $result;
    close $fh;
}
